/** Run against the synthetic API only. Attach to an isolated agent-browser session. */
const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const browser = await chromium.connectOverCDP(process.argv[2]);
  const page = browser.contexts()[0].pages().find((item) => item.url().startsWith('http://127.0.0.1:3100'));
  assert(page, 'Open the isolated preview on port 3100 first.');
  page.setDefaultTimeout(15000);
  page.setDefaultNavigationTimeout(20000);
  const cancel = page.getByRole('button', { name: 'Cancelar', exact: true });
  if (await cancel.count()) await cancel.click();
  const clear = page.getByRole('button', { name: 'Limpar todos os filtros' });
  if (await clear.count()) await clear.click();
  const collapse = page.getByRole('button', { name: /^Recolher filtros/ });
  if (await collapse.count()) await collapse.click();
  await page.getByLabel('Data da operação').fill('2026-10-03');
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const productionRequests = [];
  page.on('request', (request) => { if (/railway|hetzner/.test(request.url())) productionRequests.push(request.url()); });
  const notes = page.locator('.invoice-conference-card');
  await notes.first().waitFor();
  await page.waitForFunction(() => document.querySelectorAll('.invoice-conference-card').length === 300);
  assert.equal(await notes.count(), 300);
  const report = { viewports: [], checks: [] };
  for (const theme of ['light', 'dark']) {
    const current = await page.locator('html').getAttribute('data-theme');
    if (current !== theme) await page.getByRole('switch', { name: theme === 'light' ? 'Ativar tema claro' : 'Ativar tema escuro' }).first().click();
    for (const width of [360, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 1000 });
      await page.evaluate(() => window.scrollTo(0, 0));
      await page.screenshot({ path: `/tmp/kp-notas-${theme}-${width}.png` });
      const dimensions = await page.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth }));
      assert(dimensions.content <= dimensions.viewport, JSON.stringify(dimensions));
      report.viewports.push({ theme, ...dimensions });
      console.log('viewport', theme, width, 'OK');
    }
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByLabel('Produto', { exact: true }).fill('4577');
  await page.getByRole('combobox', { name: 'Empresa atendida' }).selectOption('mar_e_rio');
  await page.getByText('100 itens correspondentes em 100 notas.', { exact: false }).waitFor();
  assert.equal(await notes.count(), 100);
  assert.equal(await page.locator('.conference-product-row').count(), 100);
  assert.match(await notes.first().innerText(), /12,75 KG/);
  await notes.first().scrollIntoViewIfNeeded();
  await page.screenshot({ path: '/tmp/kp-notas-mobile-conferencia.png' });
  const previousY = await page.evaluate(() => window.scrollY);
  await notes.first().getByRole('button', { name: 'Mostrar detalhes da NF 10001' }).click();
  await page.getByRole('button', { name: 'Voltar para frente do card da NF 10001' }).click();
  assert.equal(await page.getByLabel('Produto', { exact: true }).inputValue(), '4577');
  assert(Math.abs(await page.evaluate(() => window.scrollY) - previousY) < 5);
  report.checks.push('Product matches, quantities, units, company scope and in-place details');
  await page.getByRole('button', { name: 'Mais filtros' }).click();
  const cityToggle = page.getByRole('button', { name: 'Filtrar cidades' });
  if (!(await cityToggle.evaluate((element) => element.closest('details').open))) await cityToggle.click();
  await page.getByLabel('Campinas', { exact: true }).check();
  assert.equal(await page.getByLabel('Produto', { exact: true }).inputValue(), '4577');
  await page.getByRole('button', { name: 'Recolher filtros' }).click();
  await notes.first().scrollIntoViewIfNeeded();
  await notes.first().getByRole('button', { name: 'Atribuir NF 10001 a uma rota' }).click();
  await page.getByRole('button', { name: 'Viagem #77 · Motorista de teste' }).click();
  await page.getByRole('button', { name: 'Confirmar atribuição', exact: true }).click();
  await page.getByText('Falha de teste: preenchimento deve ser preservado.').waitFor();
  assert.equal(await page.getByRole('button', { name: 'Viagem #77 · Motorista de teste' }).getAttribute('aria-pressed'), 'true');
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
  report.checks.push('Assignment failure preserves selected trip');
  await notes.nth(5).scrollIntoViewIfNeeded();
  const y = await page.evaluate(() => window.scrollY);
  await notes.nth(5).getByRole('button', { name: /Ver jornada/ }).click();
  await page.waitForURL(/journey/);
  await page.goBack();
  await page.getByText(/itens correspondentes em/).waitFor();
  await page.waitForFunction((target) => Math.abs(window.scrollY - target) < 5, y);
  assert.equal(await page.getByLabel('Produto', { exact: true }).inputValue(), '4577');
  report.checks.push('Journey navigation restores filters and list position');
  await page.getByRole('button', { name: 'Limpar todos os filtros' }).click();
  await page.getByLabel('Data da operação').fill('2026-01-01');
  await page.getByText('Nenhuma nota nesta operação', { exact: true }).waitFor();
  await page.screenshot({ path: '/tmp/kp-notas-empty.png' });
  await page.getByLabel('Data da operação').fill('2026-01-02');
  await page.getByText('Não foi possível carregar a operação', { exact: true }).waitFor();
  assert.equal(await page.getByText('Nenhuma nota nesta operação', { exact: true }).count(), 0);
  await page.screenshot({ path: '/tmp/kp-notas-error.png' });
  await page.getByLabel('Data da operação').fill('2026-10-03');
  await notes.first().waitFor();
  assert.equal(await notes.count(), 300);
  report.checks.push('Empty and error states are distinct; date change recovers');
  assert.deepEqual(errors, []);
  assert.deepEqual(productionRequests, []);
  console.log(JSON.stringify({ ...report, errors, productionRequests }, null, 2));
  await browser.close();
})().catch((error) => { console.error(error); process.exit(1); });
